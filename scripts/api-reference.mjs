/**
 * scripts/api-reference.mjs
 * -------------------------
 * Emit a complete method reference for both API surfaces by reading the
 * generated modules. Run it after `npm run codegen`.
 *
 *   node scripts/api-reference.mjs
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = dirname(dirname(fileURLToPath(import.meta.url)));

const TARGETS = [
  {
    title: "Forum API reference",
    source: "src/forum/_generated.ts",
    output: "docs/api-forum.md",
    className: "ForumAPI",
    clientName: "Forum",
    baseUrl: "https://prod-api.lolz.live",
  },
  {
    title: "Market API reference",
    source: "src/market/_generated.ts",
    output: "docs/api-market.md",
    className: "MarketAPI",
    clientName: "Market",
    baseUrl: "https://prod-api.lzt.market",
  },
];

/**
 * Pull one record per method out of a generated module.
 *
 * The generator always emits a doc comment whose last content line is the
 * route in backticks, immediately followed by the method signature.
 */
function parseMethods(source) {
  const methods = [];
  const lines = source.split("\n");

  for (let index = 0; index < lines.length; index += 1) {
    const signature = /^ {2}([A-Za-z_$][\w$]*)\(/.exec(lines[index]);
    if (!signature) continue;

    let summary = "";
    let route = "";
    let deprecated = false;

    for (let back = index - 1; back >= 0; back -= 1) {
      const line = lines[back].trim();
      if (line === "*/") continue;
      if (line === "/**") break;
      if (!line.startsWith("*")) break;
      const content = line.replace(/^\*\s?/, "").trim();
      if (content === "@deprecated") deprecated = true;
      const routeMatch = /^`([A-Z]+) (\/\S*)`$/.exec(content);
      if (routeMatch && !route) route = `${routeMatch[1]} ${routeMatch[2]}`;
      if (content && !content.startsWith("@") && !content.startsWith("`")) summary = content;
    }

    const hasParameters = !lines[index].includes("()");
    methods.push({ name: signature[1], route, summary, deprecated, hasParameters });
  }

  return methods;
}

/** Group methods by the prefix of their operation id, for example `Threads`. */
function groupMethods(methods) {
  const groups = new Map();
  for (const method of methods) {
    const group = method.name.includes("_") ? method.name.split("_")[0] : "General";
    if (!groups.has(group)) groups.set(group, []);
    groups.get(group).push(method);
  }
  return groups;
}

function escapeCell(text) {
  return text.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

function renderDocument(target, methods) {
  const groups = groupMethods(methods);
  const lines = [
    `# ${target.title}`,
    "",
    `Base URL: \`${target.baseUrl}\``,
    "",
    `Every method below is available on the \`${target.clientName}\` client and on the`,
    `generated \`${target.className}\` class it extends. Methods return the raw \`Response\`,`,
    "so call `.json()` on the result to read the payload.",
    "",
    `Total methods: **${methods.length}**.`,
    "",
    "This file is generated by `npm run docs`. Do not edit it by hand.",
    "",
    "## Contents",
    "",
  ];

  for (const [group, items] of groups) {
    lines.push(`- [${group}](#${group.toLowerCase()}) (${items.length})`);
  }

  for (const [group, items] of groups) {
    lines.push("", `## ${group}`, "", "| Method | Route | Description |", "| --- | --- | --- |");
    for (const method of items) {
      const name = `\`${method.name}(${method.hasParameters ? "params" : ""})\``;
      const route = method.route ? `\`${method.route}\`` : "";
      const description = escapeCell(method.summary) + (method.deprecated ? " (deprecated)" : "");
      lines.push(`| ${name} | ${route} | ${description} |`);
    }
  }

  lines.push("");
  return lines.join("\n");
}

await mkdir(join(root, "docs"), { recursive: true });

for (const target of TARGETS) {
  const source = await readFile(join(root, target.source), "utf8");
  const methods = parseMethods(source);
  if (methods.length === 0) {
    throw new Error(`No methods found in ${target.source}. Run "npm run codegen" first.`);
  }
  await writeFile(join(root, target.output), renderDocument(target, methods), "utf8");
  process.stdout.write(`Wrote ${methods.length} methods to ${target.output}\n`);
}
